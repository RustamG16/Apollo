#!/usr/bin/env python3
"""Regenerate library/INDEX.md from skills.registry.json. Do not hand-edit INDEX.md."""
import json, os
from collections import defaultdict

LIB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
reg = json.load(open(os.path.join(LIB, "registry", "skills.registry.json"), encoding="utf-8"))

by_cat = defaultdict(list)
for r in reg:
    by_cat[r["category"]].append(r)

lines = ["# Library index", "",
         f"{len(reg)} skills. Generated by `tools/build_index.py` from "
         f"`registry/skills.registry.json` — do not hand-edit.", ""]
for cat in sorted(by_cat):
    rs = sorted(by_cat[cat], key=lambda r: r["id"])
    lines.append(f"## {cat}  ({len(rs)})")
    lines.append("")
    lines.append("| Skill | Phase | Status | Hosts | Purpose |")
    lines.append("|---|---|---|---|---|")
    for r in rs:
        flag = " 🔒" if r.get("disableModelInvocation") else ""
        purpose = r["description"].replace("|", "\\|")
        if len(purpose) > 130:
            purpose = purpose[:127] + "…"
        lines.append(f"| `{r['id']}`{flag} | {r['phase']} | {r['status']} | "
                     f"{'/'.join(h[0] for h in r['hosts'])} | {purpose} |")
    lines.append("")

lines.append("Host key: c = claude · x = codex · s = studio. 🔒 = disable-model-invocation.")
open(os.path.join(LIB, "INDEX.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"wrote INDEX.md — {len(reg)} skills, {len(by_cat)} categories")
