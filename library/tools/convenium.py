#!/usr/bin/env python3
"""convenium.py — connect convenium.design to a project, and check this machine. stdlib only.

    python library/tools/convenium.py attach <project> [--commit-olympus]
    python library/tools/convenium.py detach <project>
    python library/tools/convenium.py doctor

attach   Points a project at this convenium.design folder without copying convenium.design into it.
         - writes `.olympus/CONVENIUM.md`: where convenium.design lives on this machine, how each host
           loads it, and the read order. It is the only file that holds an absolute path.
         - adds a short fenced block to the project's AGENTS.md (created if missing) that
           sends every agent to `.olympus/CONVENIUM.md`. CLAUDE.md gets the same block unless
           it already imports AGENTS.md; a project with no CLAUDE.md gets one that does.
         - adds `.olympus/` to .gitignore, so client interviews, research and Brand DNA stay
           private. `--commit-olympus` ignores only `.olympus/CONVENIUM.md` instead.
         Idempotent: re-running refreshes the block and CONVENIUM.md (e.g. after a move).
detach   Removes the blocks, the .gitignore lines and `.olympus/CONVENIUM.md`. Run artifacts
         in `.olympus/` are left alone.
doctor   Verifies the library, then warns about things that make convenium.design behave differently
         on this machine than on another.
"""
import json, os, re, subprocess, sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
HOME = os.path.dirname(os.path.dirname(TOOLS))          # the convenium.design folder
BEGIN, END = "<!-- convenium:begin -->", "<!-- convenium:end -->"
MARKERS = ((BEGIN, END), ("<!-- apollo:begin -->", "<!-- apollo:end -->"))  # + pre-rename
GI_TAG = "# convenium.design (managed by library/tools/convenium.py)"
# Written by attach before the rename; recognised so re-attach and detach clean them up.
LEGACY_GI = ("# apollo (managed by library/tools/apollo.py)", ".olympus/APOLLO.md")
USER = os.path.expanduser("~")

POINTER = f"""{BEGIN}
## convenium.design

This project is designed with convenium.design. Before any design, brand or build work, read
`.olympus/CONVENIUM.md` — it says where convenium.design lives on this machine and what to read first.
Project evidence and decisions go in `.olympus/`, never in the convenium.design folder.
{END}"""


def pointer_md(home):
    h = home.replace("\\", "/")
    return f"""# convenium.design — connection for this project

Generated by `python library/tools/convenium.py attach`. Re-run attach after moving convenium.design.
This file holds a machine-specific path and is gitignored.

**convenium.design folder:** `{h}`

## Read first (in this order)

1. `{h}/ARCHITECTURE-ESSENTIALS.md` — one screen: what convenium.design is, the run, where things live.
2. `{h}/AGENTS.md` — the operating doctrine.
3. `{h}/START-HERE.md` — the gated workflow and the intake.

Every relative path in those files (`templates/`, `library/`, `scripts/`) is relative to the
convenium.design folder above, not to this project.

## How each host loads convenium.design

- **Claude Code, plugin (recommended):** `/plugin marketplace add {h}` then
  `/plugin install convenium-design@convenium-design`. Skills are `convenium-design:<id>`, agents `convenium-design:<name>`.
- **Claude Code, no plugin:** start the session with `claude --add-dir "{h}"`; convenium.design's
  `.claude/skills` and `.claude/agents` load from there.
- **Codex:** skills are read by path — `{h}/.agents/skills/<id>/SKILL.md` — after routing
  from `{h}/library/registry/ROUTING-DIGEST.md`; specialists are described in
  `{h}/library/agents/<name>.md`.

## Where this project's work goes

`.olympus/` in this project: `brand-dna.json` + `BRAND.md` (the client's Design DNA),
`run.json`, and the numbered run artifacts created from `{h}/templates/`.
"""


# ------------------------------------------------------------------ helpers
def read(p):
    return open(p, encoding="utf-8").read() if os.path.isfile(p) else None


def write(p, text):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def strip_block(text):
    for b, e in MARKERS:
        text = re.sub(rf"\n*{re.escape(b)}.*?{re.escape(e)}\n*", "\n\n", text, flags=re.S)
    return text.strip("\n")


def put_block(path, create_with=None):
    old = read(path)
    if old is None:
        write(path, (create_with or "") + POINTER + "\n")
        return "created"
    base = strip_block(old)
    write(path, (base + "\n\n" if base else "") + POINTER + "\n")
    return "updated"


def has_block(text):
    return any(b in text for b, _ in MARKERS)


def imports_agents(claude_text):
    return bool(re.search(r"^\s*@\.?/?AGENTS\.md\s*$", claude_text or "", re.M))


def gitignore_lines(commit_olympus):
    return [GI_TAG, ".olympus/CONVENIUM.md" if commit_olympus else ".olympus/"]


def set_gitignore(project, lines):
    p = os.path.join(project, ".gitignore")
    old = read(p) or ""
    kept = [l for l in old.splitlines() if l not in (GI_TAG, ".olympus/", ".olympus/CONVENIUM.md") + LEGACY_GI]
    body = "\n".join(kept).rstrip("\n")
    new = (body + "\n\n" if body else "") + "\n".join(lines) + "\n" if lines else (body + "\n" if body else "")
    if new != old:
        write(p, new)


# ------------------------------------------------------------------ commands
def attach(project, commit_olympus):
    project = os.path.abspath(project)
    if not os.path.isdir(project):
        sys.exit(f"not a folder: {project}")
    if os.path.samefile(project, HOME):
        sys.exit("refusing to attach convenium.design to itself")
    write(os.path.join(project, ".olympus", "CONVENIUM.md"), pointer_md(HOME))
    legacy = os.path.join(project, ".olympus", "APOLLO.md")
    if os.path.isfile(legacy):
        os.remove(legacy)
        print("  .olympus/APOLLO.md: replaced by CONVENIUM.md")
    print(f"  AGENTS.md: {put_block(os.path.join(project, 'AGENTS.md'), '# AGENTS.md' + chr(10) + chr(10))}")
    claude = os.path.join(project, "CLAUDE.md")
    ct = read(claude)
    if ct is None:
        write(claude, "@AGENTS.md\n")
        print("  CLAUDE.md: created (imports AGENTS.md)")
    elif imports_agents(ct):
        if has_block(ct):
            write(claude, strip_block(ct) + "\n")
        print("  CLAUDE.md: imports AGENTS.md - no block needed")
    else:
        print(f"  CLAUDE.md: {put_block(claude)}")
    set_gitignore(project, gitignore_lines(commit_olympus))
    print(f"  .gitignore: {'.olympus/CONVENIUM.md' if commit_olympus else '.olympus/'} ignored")
    print(f"attached {project}\n  -> {HOME}")


def detach(project):
    project = os.path.abspath(project)
    for name in ("AGENTS.md", "CLAUDE.md"):
        p = os.path.join(project, name)
        t = read(p)
        if t and has_block(t):
            rest = strip_block(t)
            write(p, rest + "\n")
            print(f"  {name}: block removed")
    for name in ("CONVENIUM.md", "APOLLO.md"):
        ap = os.path.join(project, ".olympus", name)
        if os.path.isfile(ap):
            os.remove(ap)
            print(f"  .olympus/{name}: removed (run artifacts kept)")
    set_gitignore(project, [])
    print(f"detached {project}")


def doctor():
    warn = []
    rc = subprocess.run([sys.executable, os.path.join(TOOLS, "verify.py")]).returncode
    print()
    if sys.version_info < (3, 9):
        warn.append(f"Python {sys.version.split()[0]} — convenium.design's tools need 3.9+")
    for tool, why in (("git", "cloning and updating convenium.design"), ("node", "Impeccable's scripts and convenium.design Studio (optional)")):
        if subprocess.run([tool, "--version"], capture_output=True, shell=os.name == "nt").returncode != 0:
            warn.append(f"`{tool}` not found — needed for {why}")

    projected = set()
    for rel in (".claude/skills", ".agents/skills"):
        d = os.path.join(HOME, rel)
        if os.path.isdir(d):
            projected |= {n for n in os.listdir(d) if os.path.isdir(os.path.join(d, n))}
    for rel in (".claude/skills", ".codex/skills", ".agents/skills"):
        d = os.path.join(USER, rel)
        if os.path.isdir(d):
            clash = sorted(projected & set(os.listdir(d)))
            if clash:
                warn.append(f"~/{rel} has personal skills named like convenium.design's ({', '.join(clash[:8])}"
                            f"{', ...' if len(clash) > 8 else ''}). Outside the plugin, the personal copy may win; "
                            "install convenium.design as a plugin (convenium-design:<id>) or remove the personal copies.")
    for p in (os.path.join(USER, ".claude", "agents", "apollo-run.md"), os.path.join(USER, "apollo")):
        if os.path.exists(p):
            warn.append(f"{p} is the retired V3 convenium.design; it competes with design-director (see unused/README.md)")
    if os.path.isfile(os.path.join(HOME, ".mcp.json")):
        print("info: convenium.design Studio MCP server is enabled (.mcp.json)")
    else:
        print("info: convenium.design Studio MCP server is off. To enable it in Claude Code, copy "
              ".mcp.json.example to .mcp.json; for Codex see .codex/config.example.toml.")

    tracked = subprocess.run(["git", "-C", HOME, "grep", "-l", "-I", "-E", r"[A-Za-z]:[/\\](Users|Analyst_Designer)",
                              "--", ".", ":!unused", ":!convenium-studio", ":!New_upgradePlan", ":!test_projects"],
                             capture_output=True, text=True)
    hits = [l for l in tracked.stdout.splitlines() if l.strip()]
    if hits:
        warn.append("absolute machine paths in tracked files: " + ", ".join(hits[:8]))

    for w in warn:
        print("WARN ", w)
    print("\ndoctor:", "verify FAILED" if rc else "verify clean", f"| {len(warn)} warning(s)")
    return 1 if rc else 0


def main(argv):
    if not argv or argv[0] not in ("attach", "detach", "doctor"):
        print(__doc__)
        return 2
    if argv[0] == "doctor":
        return doctor()
    if len(argv) < 2:
        print(__doc__)
        return 2
    if argv[0] == "attach":
        attach(argv[1], "--commit-olympus" in argv)
    else:
        detach(argv[1])
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
